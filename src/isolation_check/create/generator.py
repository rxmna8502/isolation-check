"""Configuration generation for isolated environments."""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import secrets
from typing import Any

from isolation_check.create.spec import CreateSpec
from isolation_check.version import MANIFEST_SCHEMA_VERSION, get_package_version


@dataclass(frozen=True)
class GeneratedEnvironmentPlan:
    """Calculated configuration plan for environment generation."""

    project_name: str
    dedicated_volume: str
    db_user: str
    db_password: str
    db_name: str
    database_url: str
    redacted_database_url: str
    app_port: int
    override_compose_rel_path: str = ".isolation-check/compose.override.yaml"
    env_rel_path: str = ".isolation-check/isolation.env"
    manifest_rel_path: str = ".isolation-check/manifest.json"


def _extract_env_dict(service_cfg: dict[str, Any]) -> dict[str, str]:
    raw_env = service_cfg.get("environment")
    result: dict[str, str] = {}
    if isinstance(raw_env, dict):
        for k, v in raw_env.items():
            result[str(k)] = str(v) if v is not None else ""
    elif isinstance(raw_env, list):
        for item in raw_env:
            if isinstance(item, str) and "=" in item:
                k, v = item.split("=", 1)
                result[k.strip()] = v.strip()
    return result


def plan_generated_environment(
    spec: CreateSpec,
    raw_compose: dict[str, Any],
    resolved_app_port: int | None = None,
) -> GeneratedEnvironmentPlan:
    """Computes all parameters, dedicated volumes, and database connection URLs."""
    project_name = spec.sanitize_compose_project_name()
    dedicated_volume = spec.dedicated_volume_name()

    db_cfg = (raw_compose.get("services") or {}).get(spec.db_service) or {}
    db_env = _extract_env_dict(db_cfg)

    db_user = db_env.get("POSTGRES_USER") or "postgres"
    db_name = db_env.get("POSTGRES_DB") or db_user or "postgres"

    # Use password from base if configured, otherwise generate a secure random password
    db_password = db_env.get("POSTGRES_PASSWORD")
    if not db_password:
        db_password = secrets.token_urlsafe(16)

    database_url = f"postgresql://{db_user}:{db_password}@{spec.db_service}:5432/{db_name}"
    redacted_url = f"postgresql://{db_user}:[REDACTED]@{spec.db_service}:5432/{db_name}"

    app_port = resolved_app_port if resolved_app_port is not None else (spec.app_port or 3000)

    return GeneratedEnvironmentPlan(
        project_name=project_name,
        dedicated_volume=dedicated_volume,
        db_user=db_user,
        db_password=db_password,
        db_name=db_name,
        database_url=database_url,
        redacted_database_url=redacted_url,
        app_port=app_port,
    )


def build_override_compose_content(
    spec: CreateSpec,
    plan: GeneratedEnvironmentPlan,
    raw_compose: dict[str, Any],
    host_port: int | None = None,
) -> str:
    """Generates the override Compose YAML configuration content."""
    lines: list[str] = [
        "# Generated by isolation-check -- DO NOT COMMIT TO VERSION CONTROL",
        f"name: {plan.project_name}",
        "",
        "services:",
        f"  {spec.db_service}:",
        "    volumes:",
        f"      - {plan.dedicated_volume}:/var/lib/postgresql/data",
    ]

    # If base PostgreSQL defined host published ports and publish_db is False, reset ports
    db_cfg = (raw_compose.get("services") or {}).get(spec.db_service) or {}
    base_ports = db_cfg.get("ports")
    if base_ports and not spec.publish_db:
        lines.append("    ports: !reset []")

    # If password was generated, provide it in db environment
    db_env = _extract_env_dict(db_cfg)
    if "POSTGRES_PASSWORD" not in db_env:
        lines.extend([
            "    environment:",
            f"      POSTGRES_PASSWORD: {plan.db_password}",
        ])

    host_port_str = str(host_port) if host_port is not None else "0"
    lines.extend([
        f"  {spec.app_service}:",
        "    environment:",
        f"      {spec.db_env_var}: {plan.database_url}",
        "    ports: !override",
        f"      - \"127.0.0.1:{host_port_str}:{plan.app_port}\"",
        "",
        "volumes:",
        f"  {plan.dedicated_volume}:",
        f"    name: {plan.dedicated_volume}",
        "",
    ])

    return "\n".join(lines)


def write_generated_environment_files(
    spec: CreateSpec,
    plan: GeneratedEnvironmentPlan,
    raw_compose: dict[str, Any],
    base_commit: str,
) -> list[Path]:
    """Writes all override and manifest files into the worktree.

    Sets restrictive file permissions on files containing credentials.
    Returns list of created file paths.
    """
    wt = spec.worktree_path
    iso_dir = wt / ".isolation-check"
    iso_dir.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(iso_dir, 0o700)
    except OSError:
        pass

    created_paths: list[Path] = []

    # 1. Override compose YAML
    override_file = wt / plan.override_compose_rel_path
    override_content = build_override_compose_content(spec, plan, raw_compose)
    override_file.write_text(override_content, encoding="utf-8")
    try:
        os.chmod(override_file, 0o600)
    except OSError:
        pass
    created_paths.append(override_file)

    # 2. Private env file
    env_file = wt / plan.env_rel_path
    env_content = (
        "# Generated by isolation-check -- Untracked environment configuration\n"
        f"COMPOSE_PROJECT_NAME={plan.project_name}\n"
        f"{spec.db_env_var}={plan.database_url}\n"
        f"ISOLATION_CHECK_ENV={spec.name}\n"
    )
    env_file.write_text(env_content, encoding="utf-8")
    try:
        os.chmod(env_file, 0o600)
    except OSError:
        pass
    created_paths.append(env_file)

    # 3. Versioned ownership manifest (NO plaintext credentials)
    manifest_file = wt / plan.manifest_rel_path
    manifest_data = {
        "schema_version": "1.0",
        "manifest_schema_version": MANIFEST_SCHEMA_VERSION,
        "tool": "isolation-check",
        "tool_version": get_package_version(),
        "created_at": datetime.now(timezone.utc).isoformat(),
        "environment": {
            "name": spec.name,
            "branch": spec.branch,
            "worktree_path": str(spec.worktree_path),
            "source_repo": str(spec.repo),
            "base_ref": spec.base_ref,
            "base_commit": base_commit,
        },
        "compose": {
            "project_name": plan.project_name,
            "base_compose_files": spec.compose_files,
            "override_file": plan.override_compose_rel_path,
            "env_file": plan.env_rel_path,
        },
        "database": {
            "service_name": spec.db_service,
            "volume_name": plan.dedicated_volume,
            "mount_target": "/var/lib/postgresql/data",
            "host_ports_published": spec.publish_db,
        },
        "application": {
            "service_name": spec.app_service,
            "app_port": plan.app_port,
            "binding_policy": "loopback-only",
            "bind_address": "127.0.0.1",
            "database_env_var": spec.db_env_var,
            "database_url_redacted": plan.redacted_database_url,
        },
        "managed_files": [
            plan.override_compose_rel_path,
            plan.env_rel_path,
            plan.manifest_rel_path,
        ],
    }
    manifest_file.write_text(json.dumps(manifest_data, indent=2), encoding="utf-8")
    try:
        os.chmod(manifest_file, 0o600)
    except OSError:
        pass
    created_paths.append(manifest_file)

    return created_paths
